// Emoji and symbol glyphs used as decorative icons (✅ ❌ ⚠ 🔒 ✓ ▶ ↩ ➡ …).
const ICON_GLYPHS = /(?:[\p{Extended_Pictographic}✓✔▶↩➡➕](?:️|‍[\p{Extended_Pictographic}♀♂])*)+\s*/gu

/** Removes icon-like glyphs from user-facing text. */
export function stripIcons(text) {
  if (typeof text !== 'string') return text
  ICON_GLYPHS.lastIndex = 0
  if (!ICON_GLYPHS.test(text)) return text
  ICON_GLYPHS.lastIndex = 0
  return text.replace(ICON_GLYPHS, '').replace(/\s{2,}/g, ' ').trim()
}

export function PreferencesProvider({ children }) {
  const [theme, setTheme] = useState(() => {
    try { return localStorage.getItem(THEME_KEY) === 'dark' ? 'dark' : 'light' } catch (error) {
      console.warn('Unable to read the saved theme preference:', error)
      return 'light'
    }
  })
  const [language, setLanguage] = useState(() => {
    try {
      const saved = localStorage.getItem(LANGUAGE_KEY)
      return LANGUAGES.some((item) => item.code === saved) ? saved : 'en'
    } catch (error) {
      console.warn('Unable to read the saved language preference:', error)
      return 'en'
    }
  })

  useLayoutEffect(() => {
    document.documentElement.dataset.theme = theme
    document.documentElement.style.colorScheme = theme
    try { localStorage.setItem(THEME_KEY, theme) } catch (error) {
      console.warn('Unable to save the theme preference:', error)
    }
  }, [theme])

  useEffect(() => {
    document.documentElement.lang = language
    try { localStorage.setItem(LANGUAGE_KEY, language) } catch (error) {
      console.warn('Unable to save the language preference:', error)
    }
  }, [language])

  // Settings → General → Default language: used until the visitor picks a language themselves.
  useEffect(() => {
    let chosen = false
    try { chosen = localStorage.getItem(LANGUAGE_CHOSEN_KEY) === '1' } catch { /* storage blocked */ }
    if (chosen) return
    let alive = true
    loadPlatformInfo().then((info) => {
      const platformDefault = info?.language
      if (alive && LANGUAGES.some((item) => item.code === platformDefault)) setLanguage(platformDefault)
    })
    return () => { alive = false }
  }, [])

  const chooseLanguage = useCallback((code) => {
    try { localStorage.setItem(LANGUAGE_CHOSEN_KEY, '1') } catch { /* storage blocked */ }
    setLanguage(code)
  }, [])

  const t = useCallback((text) => stripIcons(
    platformTranslations[language]?.[text]
    || translations[language]?.[text]
    || sharedTranslations[language]?.[text]
    || additionalTranslations[language]?.[text]
    || platformScreenTranslations[language]?.[text]
    || financeTranslations[language]?.[text]
    || serviceTranslations[language]?.[text]
    || sharedAuthTranslations[language]?.[text]
    || text
  ), [language])
  const value = useMemo(() => ({ theme, setTheme, language, setLanguage: chooseLanguage, t }), [theme, language, chooseLanguage, t])

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>
}

export function usePreferences() {
  const context = useContext(PreferencesContext)
  if (!context) throw new Error('usePreferences must be used within PreferencesProvider')
  return context
}
