import React, { useState } from 'react'
import QRCode from '../../components/QRCode'
import { useAuth } from '../../context/AuthContext'

export default function QRCodeManager() {
  const { user } = useAuth()
  const [tableCount, setTableCount] = useState(12)
  const baseUrl = typeof window !== 'undefined' ? window.location.origin : ''

  const tables = Array.from({ length: tableCount }, (_, i) => i + 1)

  const handleCountChange = (e) => {
    const val = Number(e.target.value)
    if (Number.isNaN(val)) return
    setTableCount(Math.max(1, Math.min(99, Math.floor(val))))
  }

  return (
    <div className="page qr-manager">
      <div className="user-page-heading">
        <div>
          <p className="eyebrow">Table QR codes</p>
          <h1>QR Code Manager</h1>
          <p>
            Print these QR codes and place one on each table. When a customer scans a code with
            their phone camera, they are taken straight to the digital menu for that table and can
            order without waiting for a waiter.
          </p>
        </div>
      </div>

      <div className="qr-controls no-print">
        <label className="qr-count-label">
          Number of tables
          <input
            type="number"
            min="1"
            max="99"
            value={tableCount}
            onChange={handleCountChange}
            aria-label="Number of tables"
          />
        </label>
        <button type="button" className="primary-btn" onClick={() => window.print()}>
          🖨 Print all QR codes
        </button>
        <span className="qr-operator">Generated by: {user ? `${user.name} (${user.role})` : '—'}</span>
      </div>

      <div className="qr-grid">
        {tables.map((t) => {
          const bizParam = user?.businessId ? `&businessId=${user.businessId}` : ''
          const url = `${baseUrl}/menu?table=${t}${bizParam}`
          return (
            <div className="qr-card" key={t}>
              <QRCode value={url} size={190} level="M" />
              <div className="qr-meta">
                <strong className="qr-table-label">Table {t}</strong>
              </div>
            </div>
          )
        })}
      </div>
    </div>
  )
}
